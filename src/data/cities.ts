export function resolveCity(region: string, country: string): string | null {
  const byCountry = REGION_TO_CITY[`${region}@${country}`];
  if (byCountry) return byCountry;
  const plain = REGION_TO_CITY[region];
  if (plain) return plain;
  // city-name match (e.g. region "Naples" → naples)
  const lower = region.trim().toLowerCase();
  for (const [id, c] of Object.entries(CITIES)) {
    if (c.country === country && (c.en.toLowerCase() === lower || id === lower)) return id;
  }
  return NATIONAL_HUB[country] ?? null;
}

export function cityName(id: string, lang: Lang): string {
  const c = CITIES[id];
  if (!c) return id;
  return lang === "fa" ? c.fa : lang === "ar" ? c.ar : c.en;
}
